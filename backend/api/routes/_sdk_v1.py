"""Developer SDK v1 REST endpoints.

Provides external-facing lesson query, failure recording, and feedback APIs
over the ``/api/v1/sdk/*`` prefix.  The record-failure and feedback endpoints
are protected by API token authentication when configured.
"""

from __future__ import annotations

import logging

from fastapi import APIRouter, Depends, Request

from backend.api.routes._legacy import require_api_token

logger = logging.getLogger("failure_memory.api.sdk_v1")

router = APIRouter(prefix="/v1/sdk", tags=["Developer SDK v1"])


# --------------------------------------------------------------------------- #
# Query lessons — public read endpoint
# --------------------------------------------------------------------------- #

@router.post("/query-lessons")
async def query_lessons(request: Request) -> dict:
    """Retrieve gated prevention lessons matching a task description.

    Filters by ``project_id`` and ``min_confidence``, returns up to ``top_k``
    lessons ranked by relevance.
    """
    from backend.api.schemas.sdk import (
        LessonDTO,
        QueryLessonsRequest,
        QueryLessonsResponse,
    )

    body = await request.json()
    payload = QueryLessonsRequest(**body)

    runtime_manager = request.app.state.runtime_manager
    if not runtime_manager.available():
        raise RuntimeError("failure-memory storage is unavailable")
    rt = runtime_manager.require()

    # Build a retrieval query and search the store.
    from backend.memory.models import RetrievalQuery

    q = RetrievalQuery(
        text=payload.task_description,
        min_score=payload.min_confidence,
        limit=payload.top_k,
    )
    retriever = rt.retriever or rt._retriever  # noqa: SLF001
    results = retriever.retrieve(q) if retriever else []

    lessons_found = len(results)
    lessons = []
    for r in results[: payload.top_k]:
        mem = r.memory
        lessons.append(
            LessonDTO(
                lesson_id=mem.id,
                failure_mode=mem.failure_category.value,
                lesson_text=mem.lesson or "",
                prevention_action=mem.prevention or "",
                confidence_score=mem.confidence,
                verified=(mem.cause_status.value == "confirmed"),
            )
        )

    return {
        "query": payload.task_description,
        "lessons_found": lessons_found,
        "lessons": [l.model_dump() for l in lessons],
    }


# --------------------------------------------------------------------------- #
# Record failure — protected mutation endpoint
# --------------------------------------------------------------------------- #

@router.post("/record-failure")
async def record_failure(request: Request) -> dict:
    """Ingest an execution trace + error, run root-cause analysis, and store a lesson.

    Returns the extracted lesson details including confidence score and whether
    the root cause was verified by evidence.
    """
    from backend.api.schemas.sdk import RecordFailureRequest, RecordFailureResponse
    from backend.domain import OutcomeType, utcnow

    body = await request.json()
    payload = RecordFailureRequest(**body)

    runtime_manager = request.app.state.runtime_manager
    if not runtime_manager.available():
        raise RuntimeError("failure-memory storage is unavailable")
    rt = runtime_manager.require()

    from backend.agent.environment import SimulatedEnvironment
    from backend.agent.models import ExecutionRecord, Plan
    from backend.analysis.failure_analyzer import FailureAnalyzer

    # Build a synthetic execution record from the provided trace.
    env = SimulatedEnvironment(
        id=f"sdk-{payload.project_id}",
        config={},
        secrets={},
    )
    plan = Plan(task=payload.task_input, task_type="generic", steps=[])
    analyzer = FailureAnalyzer(rt.settings)

    record = ExecutionRecord(
        execution_id="",  # will be regenerated by the analyzer
        task=payload.task_input,
        task_type="generic",
        mode="sdk",
        environment_id=env.id,
        plan=plan,
        outcome=OutcomeType.TASK_FAILURE,
        success=False,
        attempts=1,
        retries=0,
        error=payload.error_message,
        started_at=utcnow(),
        finished_at=utcnow(),
    )

    analysis = analyzer.analyze(record)
    memory_id, created = rt.store.save_failure_memory(
        analysis=analysis,
        execution_record=record,
        task_type="generic",
        agent_id=payload.agent_id,
    )

    return {
        "lesson_id": memory_id or "",
        "root_cause": analysis.root_cause if analysis else payload.error_message,
        "lesson_extracted": analysis.lesson if analysis and analysis.lesson else "",
        "confidence_score": analysis.confidence if analysis else 0.5,
        "is_verified": (analysis.cause_status.value == "confirmed") if analysis else False,
    }


# --------------------------------------------------------------------------- #
# Feedback — protected mutation endpoint
# --------------------------------------------------------------------------- #

@router.post("/feedback", dependencies=[Depends(require_api_token)])
async def submit_feedback(request: Request) -> dict:
    """Update lesson confidence and UCB1 bandit weights based on execution outcome.

    When ``task_success`` is True the memory's success count and helpful_count
    are incremented; when False, failure_count and unhelpful_count increase.
    The adaptive retrieval strategy selector also receives an outcome signal.
    """
    from backend.api.schemas.sdk import FeedbackRequest as SdkFeedbackRequest

    body = await request.json()
    payload = SdkFeedbackRequest(**body)

    runtime_manager = request.app.state.runtime_manager
    if not runtime_manager.available():
        raise RuntimeError("failure-memory storage is unavailable")
    rt = runtime_manager.require()

    # Record feedback on the memory.
    from backend.memory.models import MemoryFeedback, FeedbackVerdict

    verdict = (
        FeedbackVerdict.USEFUL
        if payload.task_success
        else FeedbackVerdict.UNHELPFUL
    )
    fb = MemoryFeedback(
        id="",  # store will assign
        memory_id=payload.lesson_id,
        verdict=verdict,
        comment=f"task_success={payload.task_success}",
        execution_id=None,
        applied=True,
    )

    rt.store.add_feedback(fb)
    if payload.project_id:
        rt.store.record_use(
            payload.lesson_id,
            success=payload.task_success,
            agent_id=payload.agent_id,
        )

    return {
        "lesson_id": payload.lesson_id,
        "verdict": verdict.value,
        "success": True,
    }


